# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

DB_ENGINE = os.getenv('DB_ENGINE', 'sqlite').strip().lower()
MYSQL_MIGRATION_ENABLED = os.getenv('MYSQL_MIGRATION_ENABLED', '').strip() == '1'
if DB_ENGINE == 'mysql' or MYSQL_MIGRATION_ENABLED:
    required = ['MYSQL_DATABASE', 'MYSQL_USER', 'MYSQL_PASSWORD']
    if any(not os.getenv(key) for key in required):
        raise ImproperlyConfigured('MySQL requires MYSQL_DATABASE, MYSQL_USER and MYSQL_PASSWORD.')
    try:
        mysql_port = int(os.getenv('MYSQL_PORT', '3306'))
    except ValueError as exc:
        raise ImproperlyConfigured('MYSQL_PORT must be an integer.') from exc
    if not 1 <= mysql_port <= 65535:
        raise ImproperlyConfigured('MYSQL_PORT must be between 1 and 65535.')
    mysql_database = {
        'ENGINE': 'django.db.backends.mysql',
        'NAME': os.environ['MYSQL_DATABASE'],
        'USER': os.environ['MYSQL_USER'],
        'PASSWORD': os.environ['MYSQL_PASSWORD'],
        'HOST': os.getenv('MYSQL_HOST', '127.0.0.1'),
        'PORT': mysql_port,
        'OPTIONS': {
            'charset': 'utf8mb4',
            'init_command': "SET sql_mode='STRICT_TRANS_TABLES,NO_ENGINE_SUBSTITUTION'",
            'isolation_level': 'read committed',
        },
    }
if DB_ENGINE == 'mysql':
    database = mysql_database
elif DB_ENGINE == 'sqlite':
    database = {
        'ENGINE': 'django.db.backends.sqlite3',
        'NAME': Path(os.getenv('DATABASE_PATH', str(BASE_DIR / 'db.sqlite3'))),
    }
else:
    raise ImproperlyConfigured('DB_ENGINE must be sqlite or mysql.')
DATABASES = {'default': database}
if MYSQL_MIGRATION_ENABLED and DB_ENGINE == 'sqlite':
    DATABASES['mysql_target'] = mysql_database


